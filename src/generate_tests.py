# Generate one test per reaction
for r in reactions:
    rid = r["id"]
    wf0 = r["watch_for"][0]
    wf1 = r["watch_for"][1]
    timing_str = r["timing"]
    timing_int = trigger_map[timing_str]
    override = r["override_effect"]

    t0 = trait_by_id.get(wf0)
    t1 = trait_by_id.get(wf1)

    t0_trigger_int = trigger_map[t0["trigger"]] if t0 else timing_int
    t1_trigger_int = trigger_map[t1["trigger"]] if t1 else timing_int
    t0_effect = t0["effect_type"] if t0 else "Damage"
    t0_value = t0["effect_value"] if t0 else 1
    t1_effect = t1["effect_type"] if t1 else "Damage"
    t1_value = t1["effect_value"] if t1 else 1

    func_name = "test_reaction_" + rid
    lines2.append(f'func {func_name}() -> void:')
    lines2.append(f'\tvar by_id := _load_traits_by_id()')
    lines2.append(f'\tvar rx_by_id := _load_reactions_by_id()')
    lines2.append(f'\t# Load the reaction')
    lines2.append(f'\tvar reaction: Resource = rx_by_id["{rid}"]')
    lines2.append(f'\tassert_that(reaction).is_not_null()')
    lines2.append(f'\t# Build stubs for watch_for traits at the reaction timing so the reaction fires')
    lines2.append(f'\tvar t0_res: Resource')
    lines2.append(f'\tvar t1_res: Resource')
    lines2.append(f'\tif by_id.has("{wf0}"):')
    lines2.append(f'\t\tt0_res = by_id["{wf0}"]')
    lines2.append(f'\telse:')
    lines2.append(f'\t\tt0_res = _make_trait_stub("{wf0}", {timing_int}, "{t0_effect}", {t0_value})')
    lines2.append(f'\tif by_id.has("{wf1}"):')
    lines2.append(f'\t\tt1_res = by_id["{wf1}"]')
    lines2.append(f'\telse:')
    lines2.append(f'\t\tt1_res = _make_trait_stub("{wf1}", {timing_int}, "{t1_effect}", {t1_value})')
    lines2.append(f'\t# Card has both watch_for traits')
    lines2.append(f'\tvar card := _make_card2(t0_res, t1_res)')
    lines2.append(f'\tvar state := BattleStateScript.new()')
    lines2.append(f'\tstate.reactions = [reaction]')
    lines2.append(f'\tvar emitter := EmitScript.new()')
    lines2.append(f'\temitter.emit(state, {timing_int}, card)  # {timing_str}')
    lines2.append(f'\t# Reaction fires and returns early — exactly 1 log entry')
    lines2.append(f'\tassert_int(state.trait_fire_log.size()).is_equal(1)')
    lines2.append(f'\tvar entry := state.trait_fire_log[0]')
    lines2.append(f'\tassert_str(entry["source"]).is_equal("reaction")')
    lines2.append(f'\tassert_str(entry["effect_type"]).is_equal("{override}")')
    lines2.append(f'\t# Parent trait default effects were NOT logged (no source=="trait" entries)')
    lines2.append(f'\tfor e in state.trait_fire_log:')
    lines2.append(f'\t\tassert_str(e["source"]).is_not_equal("trait")')
    lines2.append('')

